ALTER TABLE questionnaires FORCE ROW LEVEL SECURITY;
ALTER TABLE responses FORCE ROW LEVEL SECURITY;
ALTER TABLE gap_profiles FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS questionnaires_tenant_isolation ON questionnaires;
CREATE POLICY questionnaires_tenant_isolation
ON questionnaires
USING (tenant_id = current_setting('app.current_tenant_id', true)::uuid)
WITH CHECK (tenant_id = current_setting('app.current_tenant_id', true)::uuid);

DROP POLICY IF EXISTS responses_tenant_isolation ON responses;
CREATE POLICY responses_tenant_isolation
ON responses
USING (tenant_id = current_setting('app.current_tenant_id', true)::uuid)
WITH CHECK (tenant_id = current_setting('app.current_tenant_id', true)::uuid);

DROP POLICY IF EXISTS gap_profiles_tenant_isolation ON gap_profiles;
CREATE POLICY gap_profiles_tenant_isolation
ON gap_profiles
USING (tenant_id = current_setting('app.current_tenant_id', true)::uuid)
WITH CHECK (tenant_id = current_setting('app.current_tenant_id', true)::uuid);
